// SINGLE EMISSION PATH for per-component `.showcase.tsx` companions (issue #567).
//
// The AST-based showcase generator — attribution-scoped CVA combos, prop-attr
// escaping, boolean-axis `{true}`/`{false}` emission, FnMarker (JSX / arrow /
// call) support, carried-ref import emission — lifted out of the pack script
// (`packs/next-react/files/scripts/generate-showcase-companion.ts`) into the
// CLI as a narrow module: component source text in, showcase TSX out.
//
// The CLI's generated-integrity reconform path (heal's GEN-001/GEN-002 check)
// regenerates through here; the regex-based regenerator it replaces is gone.
// This module owns the SINGLE `toPascalCase` helper and the SINGLE
// primary-component selection rule — every other CLI copy delegates here.
//
// The byte-for-byte equivalence with the pack script (the anti-ping-pong
// invariant: a CLI regen must not differ from a consumer's pack-generated
// showcase, or heal would rewrite a clean tree forever) is pinned by the golden
// test `tests/integration/showcase-golden.test.ts`. The pack script is untouched in
// this slice; a later slice reduces it to a shim over this module.
//
// Unlike the pack script (which runs under `node --experimental-strip-types` in
// a consumer that may lack `typescript`, and so inlines the CVA analyzer and
// keeps a regex fallback), the CLI always has `typescript` and imports the
// analyzer from its source of truth — so there is no runtime-resolution shim
// and no regex fallback here.

