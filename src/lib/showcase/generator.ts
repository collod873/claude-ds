function showcaseHeader(sourceName: string): string {
	return `// @generated by claude-ds — do not edit. Source: ${sourceName} meta block.`;
}

// ── helpers ───────────────────────────────────────────────────────────────────

/**
 * Convert a kebab/snake/space-separated file basename to the PascalCase display
 * name the showcase renders. The SINGLE definition in CLI source — every other
 * caller (generated-integrity, backfill-companions, drift/cva) delegates here.
 */
export function toPascalCase(name: string): string {
	return name
		.split(/[-_\s]+/)
		.filter(Boolean)
		.map((segment) => segment.charAt(0).toUpperCase() + segment.slice(1))
		.join("");
}

/**
 * The candidate export names the showcase resolves a file's render target
 * against, in lookup order: PascalCase displayName, then the raw basename. The
 * SINGLE primary-component selection rule in CLI source.
 */
export function primaryComponentNames(file: string): string[] {
	const base = basename(file).replace(/\.[^.]+$/, "");
	return [toPascalCase(base), base];
}

/**
 * The component a file's showcase renders on: the export whose name is the
 * PascalCase of the basename, falling back to the raw basename — the generator's
 * own selection (`attribution[displayName] ?? attribution[componentName]`).
 *
 * Scoping to the render target — never the union of all exported components — is
 * what keeps the CVA-consuming fixers and the generator agreeing.
 */
export function primaryComponent(attribution: CvaAttribution, file: string): ComponentCva | null {
	for (const name of primaryComponentNames(file)) {
		const hit = attribution[name];
		if (hit) return hit;
	}
	return null;
}

/**
 * Detect whether a source file has a default export.
 * Strips line/block comments and string literals first to avoid false positives
 * from "export default" appearing in comments or string values.
 */
function hasDefaultExport(source: string): boolean {
	// Strip block comments
	let stripped = source.replace(/\/\*[\s\S]*?\*\//g, "");
	// Strip line comments
	stripped = stripped.replace(/\/\/[^\n]*/g, "");
	// Strip string literals
	stripped = stripped
		.replace(/"(?:[^"\\]|\\.)*"/g, '""')
		.replace(/'(?:[^'\\]|\\.)*'/g, "''")
		.replace(/`(?:[^`\\]|\\.)*`/g, "``");
	return /^\s*export\s+default\s+/m.test(stripped);
}

/**
 * Strip all string literals (double-quoted, single-quoted, template literals)
 * from a block of source text. Used before scanning for CVA variant keys so
 * that Tailwind modifier prefixes like `hover:`, `focus:`, `aria-expanded:`
 * inside class strings are not mistaken for variant names.
 */
function stripStringLiterals(text: string): string {
	// Replace double-quoted strings
	let result = text.replace(/"(?:[^"\\]|\\.)*"/g, '""');
	// Replace single-quoted strings
	result = result.replace(/'(?:[^'\\]|\\.)*'/g, "''");
	// Replace template literals (simple, non-nested)
	result = result.replace(/`(?:[^`\\]|\\.)*`/g, "``");
	return result;
}

