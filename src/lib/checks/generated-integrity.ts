import { readdir, readFile, stat } from "node:fs/promises";
import { join } from "node:path";
import { formatContent, resolveConsumerFormatter } from "../formatter.js";
import type { Change, Operation, PlanResult } from "../operation.js";
import type { ProjectContext } from "../project.js";
import { generateShowcase } from "../showcase/generator.js";

const GEN_TIERS = ["atoms", "composites", "patterns"] as const;
const SHOWCASE_HEADER_PREFIX = "// @generated by claude-ds";
// Client-component sources carry a `"use client";` directive, which the
// generator emits as line 1 of the companion — pushing the `@generated` header
// to line 2 (#623). GEN-001 must tolerate that optional preamble, otherwise
// every client companion false-positives and heal never converges. The quote
// style and semicolon are optional: a consumer's formatter (e.g. Prettier with
// `singleQuote: true`, common in Next.js client-component repos) rewrites the
// generator's `"use client";` to `'use client';` on disk, so match either form
// — same tolerance the generator applies when detecting the directive.
const USE_CLIENT_PREAMBLE = /^["']use client["'];?\r?\n/;

/**
 * True when `content` carries the `@generated` header — at the top, or right
 * after the optional `"use client";` preamble the generator emits for client
 * components (#623).
 */
export function hasGeneratedHeader(content: string): boolean {
	const body = content.replace(USE_CLIENT_PREAMBLE, "");
	return body.startsWith(SHOWCASE_HEADER_PREFIX);
}
const COMPANION_SUFFIXES = [".showcase.tsx", ".test.tsx", ".stories.tsx"];
const SKIP_PATTERNS = [/^index\.ts$/, /\.logic\.ts$/, /\.d\.ts$/];

export interface GenViolation {
	ruleId: "GEN-001" | "GEN-002";
	file: string;
	message: string;
}

async function existsAt(p: string): Promise<boolean> {
	try {
		await stat(p);
		return true;
	} catch {
		return false;
	}
}

/** Outcome of the generated-integrity planner — reported on `RunReport.ops[i].outcome`. */
export interface GenIntegrityOutcome {
	violations: GenViolation[];
	/**
	 * Companion paths excluded from comparison because their source has no
	 * generable showcase the AST generator can mechanically reproduce — today a
	 * namespace-only export (`export const X = { A, B }`, not callable, #69), whose
	 * companion is hand-authored. Surfaced — not silent — so a skipped file can't
	 * hide a broken showcase behind a clean integrity report (#509). Each entry
	 * COULD be drifted; the check simply can't tell, so it names them for review.
	 */
	skipped: string[];
}

/**
 * GEN-001 / GEN-002 planner.
 *
 * - GEN-001: .showcase.tsx missing the `@generated` header → file likely
 *   hand-authored over a generated path.
 * - GEN-002: regenerating the companion in-memory produces different content
 *   from what's on disk → hand-edit drift over a generated file.
 *
 * Regeneration runs through the single showcase-emission path
 * (`src/lib/showcase/generator.ts`, issue #567) — the same AST generator the
 * pack ships, so a clean consumer's pack-generated companion is byte-identical
 * to the CLI regen and never ping-pongs. JSX-bearing examples (ADR-0026) are
 * now reproduced directly rather than skipped.
 *
 * Emits one `write` Change per drifted companion. The caller picks `run()` mode
 * (apply auto-repairs in-place; dry-run renders the diff). Detected violations
 * are surfaced as the Op's typed outcome on `RunReport.ops[i].outcome` so the
 * caller can drive scorecard logging and the dry-run check-script stderr output
 * — both are command-shaped concerns the Runner doesn't model.
 */
export type GenIntegrityOperation = Operation<GenIntegrityOutcome>;

export function planGeneratedIntegrityFixes(): GenIntegrityOperation {
	return {
		name: "generated-integrity",
		async plan(ctx: ProjectContext): Promise<PlanResult<GenIntegrityOutcome>> {
			const violations: GenViolation[] = [];
			const skipped: string[] = [];
			const changes: Change[] = [];
			const cwd = ctx.cwd;

			// #493: showcase companions live under design-system/ — consumer-linted
			// territory. Run the regenerated bytes through the consumer's formatter
			// so the on-disk (consumer-formatted) companion is compared like against
			// like — otherwise GEN-002 false-positives on pure formatting drift,
			// rewrites the file back to pack-canonical, and heal ping-pongs. When no
			// formatter is configured this is a no-op and behaviour is unchanged.
			const formatter = await resolveConsumerFormatter(cwd);

			for (const tier of GEN_TIERS) {
				const tierDir = join(cwd, "design-system", tier);
				let tierEntries: string[];
				try {
					tierEntries = await readdir(tierDir);
				} catch {
					continue;
				}

				for (const entry of tierEntries) {
					if (entry === ".keep" || entry === ".gitkeep") continue;
					if (!entry.endsWith(".tsx")) continue;
					if (COMPANION_SUFFIXES.some((s) => entry.endsWith(s))) continue;
					if (SKIP_PATTERNS.some((re) => re.test(entry))) continue;

					const entryPath = join(tierDir, entry);
					const entryStat = await stat(entryPath).catch(() => null);
					if (!entryStat || !entryStat.isFile()) continue;

					const componentName = entry.slice(0, -4);

					let source: string;
					try {
						source = await readFile(entryPath, "utf8");
					} catch {
						continue;
					}

					const showcasePath = join(tierDir, `${componentName}.showcase.tsx`);
					const showcaseRel = `design-system/${tier}/${componentName}.showcase.tsx`;

					if (!(await existsAt(showcasePath))) continue;

					const regen = generateShowcase({ filePath: entryPath, source });
					if (regen.content === null) {
						// A namespace-only export (#69) can't be mechanically regenerated.
						// Name the companion so the caller can flag it for hand review
						// (#509). A "no-meta" source is not a generated companion at all
						// and stays silent.
						if (regen.skipReason === "namespace-only") skipped.push(showcaseRel);
						continue;
					}
					const regenerated = regen.content;
					// Compare and write the consumer-formatted form (issue #493).
					const expected = formatter
						? formatContent(formatter, regenerated, showcaseRel, cwd)
						: regenerated;

					let content: string;
					try {
						content = await readFile(showcasePath, "utf8");
					} catch {
						content = "";
					}

					if (!hasGeneratedHeader(content)) {
						violations.push({
							ruleId: "GEN-001",
							file: showcaseRel,
							message: `@generated header missing from ${showcaseRel}`,
						});
						changes.push({
							kind: "write",
							path: showcaseRel,
							before: Buffer.from(content, "utf8"),
							after: Buffer.from(expected, "utf8"),
						});
					} else if (expected !== content) {
						violations.push({
							ruleId: "GEN-002",
							file: showcaseRel,
							message: `${showcaseRel} differs from regeneration — hand-edit detected`,
						});
						changes.push({
							kind: "write",
							path: showcaseRel,
							before: Buffer.from(content, "utf8"),
							after: Buffer.from(expected, "utf8"),
						});
					}
				}
			}

			return { changes, outcome: { violations, skipped } };
		},
	};
}
